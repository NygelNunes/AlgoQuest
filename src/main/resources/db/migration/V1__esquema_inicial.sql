-- AlgoQuest: esquema inicial, derivado do modelo de dominio existente
-- (Usuario, ProgressoUsuario, Modulo, Exercicio, ExercicioMultiplaEscolha, Dificuldade).
-- SQL portavel: executa em H2 (padrao) e PostgreSQL.

CREATE TABLE usuario (
    id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_usuario  VARCHAR(50)  NOT NULL,
    senha_hash    VARCHAR(255) NOT NULL,          -- PBKDF2; nunca a senha em texto puro
    pontuacao     INT          NOT NULL DEFAULT 0,
    xp            INT          NOT NULL DEFAULT 0,
    nivel         INT          NOT NULL DEFAULT 1,
    criado_em     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_usuario_nome UNIQUE (nome_usuario),
    CONSTRAINT ck_usuario_valores CHECK (pontuacao >= 0 AND xp >= 0 AND nivel >= 1)
);

CREATE TABLE modulo (
    id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo     VARCHAR(120) NOT NULL,
    descricao  VARCHAR(500) NOT NULL,
    ordem      INT          NOT NULL DEFAULT 0,
    ativo      BOOLEAN      NOT NULL DEFAULT TRUE   -- ModuloRepositorio.buscarModulosAtivos()
);

CREATE TABLE exercicio (
    id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    modulo_id       INT           NOT NULL,
    ordem           INT           NOT NULL DEFAULT 0,
    tipo            VARCHAR(30)   NOT NULL DEFAULT 'MULTIPLA_ESCOLHA',
    descricao       VARCHAR(1000) NOT NULL,
    dificuldade     VARCHAR(10)   NOT NULL,
    pontos          INT           NOT NULL,
    texto_feedback  VARCHAR(1000),
    CONSTRAINT fk_exercicio_modulo FOREIGN KEY (modulo_id) REFERENCES modulo (id) ON DELETE CASCADE,
    CONSTRAINT ck_exercicio_dificuldade CHECK (dificuldade IN ('FACIL', 'MEDIO', 'DIFICIL')),
    CONSTRAINT ck_exercicio_pontos CHECK (pontos > 0)
);
CREATE INDEX ix_exercicio_modulo ON exercicio (modulo_id);

-- ExercicioMultiplaEscolha: o indice correto fica numa tabela propria, que NUNCA e lida pelo endpoint publico.
CREATE TABLE exercicio_multipla_escolha (
    exercicio_id    INT PRIMARY KEY,
    indice_correto  INT NOT NULL,
    CONSTRAINT fk_eme_exercicio FOREIGN KEY (exercicio_id) REFERENCES exercicio (id) ON DELETE CASCADE,
    CONSTRAINT ck_eme_indice CHECK (indice_correto >= 0)
);

CREATE TABLE exercicio_opcao (
    exercicio_id  INT          NOT NULL,
    indice        INT          NOT NULL,
    texto         VARCHAR(500) NOT NULL,
    PRIMARY KEY (exercicio_id, indice),
    CONSTRAINT fk_opcao_exercicio FOREIGN KEY (exercicio_id) REFERENCES exercicio (id) ON DELETE CASCADE,
    CONSTRAINT ck_opcao_indice CHECK (indice >= 0)
);

-- ProgressoUsuario.exerciciosConcluidos: a chave primaria composta impede conclusao duplicada
-- (base da garantia de que pontos/XP nao sao concedidos duas vezes pelo mesmo exercicio).
CREATE TABLE progresso_usuario (
    usuario_id    INT       NOT NULL,
    exercicio_id  INT       NOT NULL,
    concluido_em  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (usuario_id, exercicio_id),
    CONSTRAINT fk_progresso_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id) ON DELETE CASCADE,
    CONSTRAINT fk_progresso_exercicio FOREIGN KEY (exercicio_id) REFERENCES exercicio (id) ON DELETE CASCADE
);

-- Sessoes de login: guarda apenas o SHA-256 do token (o token em si nunca e gravado).
CREATE TABLE sessao (
    token_hash  VARCHAR(64) PRIMARY KEY,
    usuario_id  INT         NOT NULL,
    criada_em   TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expira_em   TIMESTAMP   NOT NULL,
    CONSTRAINT fk_sessao_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id) ON DELETE CASCADE
);
CREATE INDEX ix_sessao_usuario ON sessao (usuario_id);
